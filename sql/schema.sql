
-- Restaurant Sales SQL Quiz
-- Step 3.1: Create business tables

CREATE TABLE IF NOT EXISTS public.restaurants (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.menu_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id INTEGER NOT NULL
        REFERENCES public.restaurants(id),
    name VARCHAR(100) NOT NULL,
    price NUMERIC(10, 2) NOT NULL
        CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS public.orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id INTEGER NOT NULL
        REFERENCES public.restaurants(id),
    menu_item_id INTEGER NOT NULL
        REFERENCES public.menu_items(id),
    quantity INTEGER NOT NULL
        CHECK (quantity > 0),
    order_date DATE NOT NULL
);



-- Step 3.4: Create SQL quiz tables

CREATE TABLE IF NOT EXISTS public.quiz_questions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    points INTEGER NOT NULL CHECK (points > 0),
    hint TEXT NOT NULL,
    expected_sql TEXT NOT NULL,
    expected_result JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.quiz_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id),
    question_id INTEGER NOT NULL
        REFERENCES public.quiz_questions(id),
    submitted_sql TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Enable Row Level Security on both tables.
ALTER TABLE public.quiz_questions
    ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.quiz_submissions
    ENABLE ROW LEVEL SECURITY;

-- Signed-in users may read the questions.
-- Public access to answer keys remains restricted.
REVOKE ALL ON public.quiz_questions
    FROM anon, authenticated;

-- Users may only read their own submissions.
CREATE POLICY "Users can view own submissions"
ON public.quiz_submissions
FOR SELECT
TO authenticated
USING ((SELECT auth.uid()) = user_id);

-- Users may only insert their own submissions.
CREATE POLICY "Users can insert own submissions"
ON public.quiz_submissions
FOR INSERT
TO authenticated
WITH CHECK ((SELECT auth.uid()) = user_id);
